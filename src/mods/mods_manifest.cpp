std::string LanguageLower()
{
	if (g_language.empty()) {
		char buf[64] = {};
		GetPrivateProfileStringA("Language", "Default", "English", buf, sizeof(buf), (GameDir() + "\\Settings.ini").c_str());
		g_language = Lower(buf);
	}
	return g_language;
}

std::string LocalizedText(const Json &j, const char *key, const std::string &def)
{
	const Json *v = j.Get(key);
	if (!v) return def;
	if (v->type == Json::String) return v->str;
	if (v->type != Json::Object) return def;
	const std::string language = LanguageLower();
	for (const std::string &want : {language, std::string("english")}) {
		for (const auto &kv : v->obj) {
			if (kv.second.type == Json::String && !kv.second.str.empty() && Lower(kv.first) == want) return kv.second.str;
		}
	}
	for (const auto &kv : v->obj) {
		if (kv.second.type == Json::String && !kv.second.str.empty()) return kv.second.str;
	}
	return def;
}
